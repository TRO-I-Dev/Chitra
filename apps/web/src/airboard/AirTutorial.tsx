function GestureCard({ meta, action }: { meta: GestureMeta; action: string }): JSX.Element {
  const canvasRef = useRef<HTMLCanvasElement | null>(null);
  const live = useLive();
  const isActive = live.present && live.action === action && action !== "none";

  useEffect(() => {
    const canvas = canvasRef.current;
    if (!canvas) return;
    const ctx = canvas.getContext("2d");
    if (!ctx) return;
    const dpr = Math.min(window.devicePixelRatio || 1, 2);
    canvas.width = canvas.clientWidth * dpr;
    canvas.height = canvas.clientHeight * dpr;
    ctx.setTransform(dpr, 0, 0, dpr, 0, 0);
    const w = canvas.clientWidth;
    const h = canvas.clientHeight;

    // Pinch gestures have no extension template, so animate the two fingers
    // closing on a neutral hand instead.
    const target =
      meta.template ??
      (meta.id === "pinch-middle" ? [0.2, 0.9, 0.15, 0.9, 0.9] : [0.15, 0.15, 0.9, 0.9, 0.9]);

    let raf = 0;
    const start = performance.now();
    const draw = (): void => {
      raf = requestAnimationFrame(draw);
      // 2.4s loop: rest → pose → hold → back.
      const t = ((performance.now() - start) % 2400) / 2400;
      const k = t < 0.35 ? t / 0.35 : t < 0.75 ? 1 : 1 - (t - 0.75) / 0.25;
      const ext = blendExtension(REST_POSE, target, easeInOut(k));
      const lms = synthesizeHand(ext, { x: 0.5, y: 0.88 }, 1);

      // A hand is square; mapping it axis-by-axis onto a wide card would
      // splay the fingers sideways.
      const { s: size, ox, oy } = stage(w, h);
      const px = (v: number): number => ox + v * size;
      const py = (v: number): number => oy + v * size;

      ctx.clearRect(0, 0, w, h);
      ctx.save();
      ctx.lineCap = "round";
      ctx.lineJoin = "round";
      ctx.strokeStyle = "rgba(124,140,255,0.85)";
      ctx.lineWidth = 2.4;
      for (const [a, b] of HAND_CONNECTIONS) {
        const pa = lms[a];
        const pb = lms[b];
        if (!pa || !pb) continue;
        ctx.beginPath();
        ctx.moveTo(px(pa.x), py(pa.y));
        ctx.lineTo(px(pb.x), py(pb.y));
        ctx.stroke();
      }
      ctx.fillStyle = "#37d3d0";
      for (const p of lms) {
        ctx.beginPath();
        ctx.arc(px(p.x), py(p.y), 2, 0, Math.PI * 2);
        ctx.fill();
      }
      ctx.restore();
    };
    raf = requestAnimationFrame(draw);
    return () => cancelAnimationFrame(raf);
  }, [meta]);

  return (
    <div
      className={[
        "rounded-xl border p-3 transition",
        isActive
          ? "border-[var(--color-accent-2)] bg-[var(--color-accent-2)]/12"
          : "border-white/10 bg-black/20",
      ].join(" ")}
    >
      <div className="mb-2 flex items-center gap-2">
        <span className="text-lg" aria-hidden="true">
          {meta.glyph}
        </span>
        <div className="min-w-0 flex-1">
          <div className="text-xs font-medium text-[var(--color-ink)]">{meta.label}</div>
          <div className="truncate text-[10px] text-[var(--color-accent)]">
            {ACTION_LABELS[action as keyof typeof ACTION_LABELS] ?? action}
          </div>
        </div>
        {isActive && (
          <span className="rounded bg-[var(--color-accent-2)] px-1.5 py-0.5 text-[9px] font-semibold text-[#0b0b10]">
            NOW
          </span>
        )}
      </div>
      <canvas ref={canvasRef} className="mb-2 h-36 w-full rounded-lg bg-black/25" />
      <p className="text-[10px] leading-relaxed text-[var(--color-ink-dim)]">{meta.instruction}</p>
    </div>
  );
}

