/** Polls the running session so every section can show live state. */
function useLive(): { present: boolean; action: string; openness: number; running: boolean } {
  const [v, setV] = useState({ present: false, action: "none", openness: 0, running: false });
  useEffect(() => {
    const id = window.setInterval(() => {
      const s = getActiveSession();
      const snap = s?.snapshot;
      setV({
        running: !!s,
        present: !!snap && !snap.lost,
        action: snap && !snap.lost ? snap.action : "none",
        openness: snap?.openness ?? 0,
      });
    }, 100);
    return () => window.clearInterval(id);
  }, []);
  return v;
}

