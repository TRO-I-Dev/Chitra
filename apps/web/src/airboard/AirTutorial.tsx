function ToolCard({
  tool,
  label,
  glyph,
  hint,
}: {
  tool: AirTool;
  label: string;
  glyph: string;
  hint: string;
}): JSX.Element {
  const canvasRef = useRef<HTMLCanvasElement | null>(null);
  const color = useAirBoard((s) => s.color);
  const snap = useAirBoard((s) => (s.profile.shapeSnap ? s.profile.shapeSnapStrength : 0));
  const setTool = useAirBoard((s) => s.setTool);
  const current = useAirBoard((s) => s.tool);

  const demo = useMemo(() => demoForTool(tool, snap), [tool, snap]);

  useEffect(() => {
    const canvas = canvasRef.current;
    if (!canvas) return;
    const ctx = canvas.getContext("2d");
    if (!ctx) return;
    const dpr = Math.min(window.devicePixelRatio || 1, 2);
    canvas.width = canvas.clientWidth * dpr;
    canvas.height = canvas.clientHeight * dpr;
    ctx.setTransform(dpr, 0, 0, dpr, 0, 0);
    const w = canvas.clientWidth;
    const h = canvas.clientHeight;

    const style = {
      stroke: tool === "laser" ? "#ff5470" : color,
      width: tool === "marker" ? 9 : 2.2,
      accent: tool === "laser" ? "#ff5470" : color,
    };

    let raf = 0;
    const start = performance.now();
    const draw = (): void => {
      raf = requestAnimationFrame(draw);
      // 3.6s loop: trace (0→.55) · flash (.55→.65) · outcome (.65→1).
      const t = ((performance.now() - start) % 3600) / 3600;
      ctx.clearRect(0, 0, w, h);

      if (tool === "eraser") {
        // The eraser needs something to erase, so the demo pre-draws ink and
        // wipes it as the "hand" sweeps through.
        const wipe = t < 0.55 ? t / 0.55 : 1;
        drawStroke(ctx, demo.stroke, w, h, 1, { ...style, stroke: "rgba(231,231,238,0.25)" }, 1);
        ctx.save();
        ctx.globalCompositeOperation = "destination-out";
        ctx.beginPath();
        const { s: sz, ox, oy } = stage(w, h);
        const p = demo.stroke[Math.floor((demo.stroke.length - 1) * wipe)]!;
        ctx.arc(ox + p.x * sz, oy + p.y * sz, 22, 0, Math.PI * 2);
        ctx.fill();
        ctx.restore();
        ctx.save();
        ctx.strokeStyle = "#ff6b8a";
        ctx.lineWidth = 2;
        ctx.beginPath();
        ctx.arc(ox + p.x * sz, oy + p.y * sz, 22, 0, Math.PI * 2);
        ctx.stroke();
        ctx.restore();
        return;
      }

      if (tool === "laser") {
        // Fading trail — nothing is ever committed.
        const { s: sz, ox, oy } = stage(w, h);
        const head = Math.floor((demo.stroke.length - 1) * t);
        for (let i = Math.max(0, head - 22); i < head; i++) {
          const a = demo.stroke[i]!;
          const b = demo.stroke[i + 1]!;
          const age = (head - i) / 22;
          ctx.save();
          ctx.globalAlpha = 1 - age;
          ctx.strokeStyle = "#ff5470";
          ctx.lineWidth = 4 * (1 - age * 0.6);
          ctx.lineCap = "round";
          ctx.beginPath();
          ctx.moveTo(ox + a.x * sz, oy + a.y * sz);
          ctx.lineTo(ox + b.x * sz, oy + b.y * sz);
          ctx.stroke();
          ctx.restore();
        }
        return;
      }

      if (t < 0.55) {
        drawStroke(ctx, demo.stroke, w, h, t / 0.55, style, tool === "marker" ? 0.45 : 1);
      } else if (t < 0.65) {
        // Brief flash at the moment of commit.
        const k = (t - 0.55) / 0.1;
        drawStroke(ctx, demo.stroke, w, h, 1, style, (1 - k) * (tool === "marker" ? 0.45 : 1));
        drawOutcome(ctx, demo, w, h, style, k);
      } else {
        drawOutcome(ctx, demo, w, h, style, 1);
      }
    };
    raf = requestAnimationFrame(draw);
    return () => cancelAnimationFrame(raf);
  }, [tool, demo, color]);

  return (
    <div
      className={[
        "rounded-xl border p-3 transition",
        current === tool
          ? "border-[var(--color-accent)]/50 bg-[var(--color-accent)]/8"
          : "border-white/10 bg-black/20",
      ].join(" ")}
    >
      <div className="mb-2 flex items-center gap-2">
        <span className="text-base" aria-hidden="true">
          {glyph}
        </span>
        <span className="flex-1 text-xs font-medium text-[var(--color-ink)]">{label}</span>
        <button
          type="button"
          onClick={() => setTool(tool)}
          className="rounded px-1.5 py-0.5 text-[9px] text-[var(--color-ink-dim)] hover:bg-white/10 hover:text-[var(--color-ink)]"
        >
          {current === tool ? "selected" : "use it"}
        </button>
      </div>
      <canvas ref={canvasRef} className="mb-2 h-28 w-full rounded-lg bg-black/30" />
      <p className="text-[10px] leading-relaxed text-[var(--color-ink-dim)]">{hint}</p>
      <p className="mt-1 text-[10px] leading-relaxed text-[var(--color-accent)]">{demo.caption}</p>
    </div>
  );
}

function ShapesSection(): JSX.Element {
  const snapStrength = useAirBoard((s) => (s.profile.shapeSnap ? s.profile.shapeSnapStrength : 0));
  const patchProfile = useAirBoard((s) => s.patchProfile);

  return (
    <>
      <Lead>
        Drawing in mid-air is shaky — there's no surface to rest against. So instead of fighting the
        tremor while you draw, Air Board waits until you finish the stroke and then works out what
        you meant. Rough loops become circles, wonky boxes become rectangles.
      </Lead>
      <Lead>
        Crucially, it refuses when it isn't sure: a shape has to both fit well <em>and</em> beat the
        runner-up interpretation, otherwise your stroke is kept as ink. Better to leave a scribble
        alone than to turn it confidently into the wrong thing.
      </Lead>

      <H3>Try the slider</H3>
      <div className="mb-3 rounded-xl border border-white/10 bg-black/20 p-3">
        <div className="mb-1 flex items-baseline justify-between text-[11px]">
          <span className="text-[var(--color-ink)]">Shape snapping</span>
          <span className="tabular-nums text-[var(--color-ink-dim)]">
            {snapStrength.toFixed(2)}
          </span>
        </div>
        <input
          type="range"
          min={0}
          max={1}
          step={0.05}
          value={snapStrength}
          onChange={(e) => {
            const v = Number(e.target.value);
            patchProfile({ shapeSnapStrength: v, shapeSnap: v > 0.01 });
          }}
          className="w-full accent-[var(--color-accent)]"
        />
        <div className="flex justify-between text-[9px] text-[var(--color-ink-dim)]">
          <span>Keep my ink</span>
          <span>Always snap</span>
        </div>
        <p className="mt-1.5 text-[10px] text-[var(--color-ink-dim)]">
          The previews below re-run live as you move it — this is the real recogniser, not a
          mock-up.
        </p>
      </div>

      <div className="grid grid-cols-3 gap-3">
        <ShapeDemo label="Rough loop" kind="circle" strength={snapStrength} />
        <ShapeDemo label="Wonky box" kind="rect" strength={snapStrength} />
        <ShapeDemo label="Real scribble" kind="scribble" strength={snapStrength} />
      </div>
      <p className="mt-3 text-[10px] leading-relaxed text-[var(--color-ink-dim)]">
        Note the third one: no matter how high you push the slider, a genuine scribble stays as ink.
        That's the ambiguity guard doing its job.
      </p>
    </>
  );
}

function ShapeDemo({
  label,
  kind,
  strength,
}: {
  label: string;
  kind: "circle" | "rect" | "scribble";
  strength: number;
}): JSX.Element {
  const canvasRef = useRef<HTMLCanvasElement | null>(null);
  const color = useAirBoard((s) => s.color);

  // Re-runs the *real* recogniser whenever the slider moves, so these panels
  // are a live readout of the algorithm rather than three static pictures.
  const demo = useMemo<ToolDemo>(() => {
    if (kind === "circle") return demoForTool("pen", strength);
    const stroke = kind === "rect" ? wobblyRect() : scribble();
    const result = recognizeNormalized(stroke, strength);
    return {
      stroke,
      outcome: { kind: "recognized", result },
      caption: result.kind === "freedraw" ? "kept as ink" : `→ ${result.kind}`,
    };
  }, [kind, strength]);

  useEffect(() => {
    const canvas = canvasRef.current;
    if (!canvas) return;
    const ctx = canvas.getContext("2d");
    if (!ctx) return;
    const dpr = Math.min(window.devicePixelRatio || 1, 2);
    canvas.width = canvas.clientWidth * dpr;
    canvas.height = canvas.clientHeight * dpr;
    ctx.setTransform(dpr, 0, 0, dpr, 0, 0);
    const w = canvas.clientWidth;
    const h = canvas.clientHeight;
    const style = { stroke: "rgba(231,231,238,0.45)", width: 1.8, accent: color };

    ctx.clearRect(0, 0, w, h);
    drawStroke(ctx, demo.stroke, w, h, 1, style, 1);
    drawOutcome(ctx, demo, w, h, style, 1);
  }, [demo, color]);

  return (
    <div className="rounded-xl border border-white/10 bg-black/20 p-2.5">
      <canvas ref={canvasRef} className="h-24 w-full rounded-lg bg-black/30" />
      <div className="mt-1.5 text-[10px] text-[var(--color-ink)]">{label}</div>
      <div className="text-[10px] text-[var(--color-accent)]">{demo.caption}</div>
    </div>
  );
}

