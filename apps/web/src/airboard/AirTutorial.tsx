/**
 * The Air Board tutorial.
 *
 * Every illustration here is generated by the production code rather than
 * drawn by hand: gesture animations are rendered from the same `template`
 * extension vectors the pose classifier matches against, and tool previews run
 * the real `recognizeShape()` on a synthetic stroke. A tutorial that mocks up
 * its examples starts lying the first time the behaviour changes; this one
 * can't, because it *is* the behaviour.
 *
 * Where the camera is live, each section also shows what the tracker is seeing
 * right now — so "here is the gesture" and "here is you doing the gesture" sit
 * side by side.
 */

type SectionId = "overview" | "cursor" | "gestures" | "tools" | "shapes" | "tips";

