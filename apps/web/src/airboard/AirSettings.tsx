import { motion } from "framer-motion";
import { useEffect, useState } from "react";
import { toast } from "sonner";

import { useAirBoard } from "./airBoardStore.js";
import { getActiveSession } from "./airSession.js";
import { ACTION_LABELS, type AirAction, GESTURES, type GestureId } from "./gestureProfile.js";
import { HandTracker } from "./handTracker.js";

/**
 * Air Board settings — gesture bindings, feel, and camera.
 *
 * Bindings are the interesting part: every action is remappable to any
 * gesture, which matters for accessibility (not everyone can pinch, or hold a
 * fist) and lets a user drop gestures they keep triggering by accident.
 */
export function AirSettings({ onClose }: { onClose: () => void }): JSX.Element {
  const profile = useAirBoard((s) => s.profile);
  const patchProfile = useAirBoard((s) => s.patchProfile);
  const resetProfile = useAirBoard((s) => s.resetProfile);
  const setCalibrationOpen = useAirBoard((s) => s.setCalibrationOpen);
  const setTutorialOpen = useAirBoard((s) => s.setTutorialOpen);
  const previewOn = useAirBoard((s) => s.previewOn);
  const setPreviewOn = useAirBoard((s) => s.setPreviewOn);
  const cameraId = useAirBoard((s) => s.cameraId);
  const setCameraId = useAirBoard((s) => s.setCameraId);
  const strokeWidth = useAirBoard((s) => s.strokeWidth);
  const setStrokeWidth = useAirBoard((s) => s.setStrokeWidth);

  const [cameras, setCameras] = useState<MediaDeviceInfo[]>([]);

  useEffect(() => {
    void HandTracker.listCameras().then(setCameras);
  }, []);

  const setBinding = (gesture: GestureId, action: AirAction): void => {
    patchProfile({ bindings: { ...profile.bindings, [gesture]: action } });
  };

  const calibratedCount = Object.values(profile.calibration).filter((c) => c?.calibratedAt).length;

  return (
    <div
      className="absolute inset-0 z-50 flex items-center justify-center bg-[#07070c]/80 p-4 backdrop-blur-sm"
      onClick={onClose}
    >
      <motion.div
        initial={{ opacity: 0, y: 12, scale: 0.98 }}
        animate={{ opacity: 1, y: 0, scale: 1 }}
        onClick={(e) => e.stopPropagation()}
        className="max-h-[86vh] w-full max-w-2xl overflow-y-auto rounded-2xl border border-white/10 bg-[var(--color-surface)] p-6 shadow-2xl"
      >
        <div className="mb-5 flex items-start justify-between">
          <div>
            <h2 className="text-base font-semibold text-[var(--color-ink)]">Air Board settings</h2>
            <p className="mt-0.5 text-xs text-[var(--color-ink-dim)]">
              {calibratedCount > 0
                ? `${calibratedCount} gesture${calibratedCount === 1 ? "" : "s"} calibrated to your hand.`
                : "Not calibrated yet — recognition is using generic defaults."}
            </p>
          </div>
          <button
            type="button"
            onClick={onClose}
            aria-label="Close"
            className="rounded p-1 text-[var(--color-ink-dim)] hover:bg-white/5 hover:text-[var(--color-ink)]"
          >
            ×
          </button>
        </div>

        {/* ---------------- tutorial ---------------- */}
        <button
          type="button"
          onClick={() => {
            setTutorialOpen(true);
            onClose();
          }}
          className="group mb-6 flex w-full items-center gap-4 rounded-2xl border border-[var(--color-accent)]/30 bg-gradient-to-br from-[var(--color-accent)]/12 to-[var(--color-accent-2)]/10 px-4 py-4 text-left transition hover:border-[var(--color-accent)]/60"
        >
          <span className="text-2xl" aria-hidden="true">
            📖
          </span>
          <span className="min-w-0 flex-1">
            <span className="block text-sm font-semibold text-[var(--color-ink)]">
              Open the field guide
            </span>
            <span className="mt-0.5 block text-[11px] leading-relaxed text-[var(--color-ink-dim)]">
              An illustrated tour of every gesture and tool, with live animated examples of what
              each one produces — generated by the real drawing engine, not mock-ups.
            </span>
          </span>
          <span className="text-[var(--color-ink-dim)] transition group-hover:translate-x-0.5 group-hover:text-[var(--color-ink)]">
            →
          </span>
        </button>

        {/* ---------------- bindings ---------------- */}
        <Section
          title="Gestures"
          hint="Bind any action to any gesture. Set an action to “nothing” to disable a gesture you keep triggering by accident."
        >
          <div className="space-y-1.5">
            {GESTURES.map((g) => {
              const cal = profile.calibration[g.id];
              return (
                <div
                  key={g.id}
                  className="flex items-center gap-3 rounded-lg border border-white/8 bg-black/15 px-3 py-2"
                >
                  <span className="w-6 text-center text-lg" aria-hidden="true">
                    {g.glyph}
                  </span>
                  <div className="min-w-0 flex-1">
                    <div className="text-xs font-medium text-[var(--color-ink)]">{g.label}</div>
                    <div className="truncate text-[10px] text-[var(--color-ink-dim)]">
                      {cal?.calibratedAt ? "calibrated" : "using defaults"}
                      {g.kind === "pinch" && cal?.onThreshold !== undefined
                        ? ` · trigger at ${cal.onThreshold.toFixed(2)}`
                        : ""}
                    </div>
                  </div>
                  <select
                    value={profile.bindings[g.id]}
                    onChange={(e) => setBinding(g.id, e.target.value as AirAction)}
                    className="rounded-md border border-white/10 bg-black/30 px-2 py-1 text-xs text-[var(--color-ink)] outline-none"
                  >
                    {(Object.keys(ACTION_LABELS) as AirAction[]).map((a) => (
                      <option key={a} value={a}>
                        {ACTION_LABELS[a]}
                      </option>
                    ))}
                  </select>
                </div>
              );
            })}
          </div>
          <button
            type="button"
            onClick={() => {
              setCalibrationOpen(true);
              onClose();
            }}
            className="mt-3 w-full rounded-lg bg-gradient-to-br from-[var(--color-accent)] to-[var(--color-accent-2)] px-4 py-2 text-xs font-semibold text-[#0b0b10]"
          >
            Run calibration
          </button>
        </Section>

        {/* ---------------- feel ---------------- */}
        <Section title="Feel" hint="How the cursor and the ink respond.">
          <Slider
            label="Smoothing"
            value={profile.smoothing}
            min={0}
            max={1}
            step={0.05}
            onChange={(v) => patchProfile({ smoothing: v })}
            left="Instant"
            right="Glassy"
            note="Higher removes hand tremor but adds a little lag."
          />
          <Slider
            label="Cursor speed"
            value={profile.sensitivity}
            min={0.6}
            max={2}
            step={0.05}
            onChange={(v) => patchProfile({ sensitivity: v })}
            left="Slow"
            right="Fast"
            note="Multiplies movement around the centre of your reach area."
          />
          <Slider
            label="Shape snapping"
            value={profile.shapeSnapStrength}
            min={0}
            max={1}
            step={0.05}
            onChange={(v) => patchProfile({ shapeSnapStrength: v, shapeSnap: v > 0.01 })}
            left="Keep my ink"
            right="Always snap"
            note="How eagerly a rough loop becomes a clean circle."
          />
          <Slider
            label="Dwell to click"
            value={profile.dwellMs}
            min={300}
            max={1600}
            step={50}
            onChange={(v) => patchProfile({ dwellMs: v })}
            left="Fast"
            right="Deliberate"
            format={(v) => `${Math.round(v)} ms`}
            note="Hold the cursor still this long to confirm without pinching."
          />
          <Slider
            label="Gesture steadiness"
            value={profile.poseDebounceFrames}
            min={1}
            max={12}
            step={1}
            onChange={(v) => patchProfile({ poseDebounceFrames: Math.round(v) })}
            left="Twitchy"
            right="Stubborn"
            format={(v) => `${Math.round(v)} frames`}
            note="Frames a pose must hold before it fires. Raise it if gestures misfire."
          />
          <Slider
            label="Stroke width"
            value={strokeWidth}
            min={1}
            max={8}
            step={0.5}
            onChange={setStrokeWidth}
            left="Fine"
            right="Bold"
            format={(v) => `${v}px`}
          />
        </Section>

        {/* ---------------- reach area ---------------- */}
        <Section
          title="Reach area"
          hint="The slice of the camera frame mapped onto the board. A smaller box means less arm movement covers the whole canvas."
        >
          <label className="mb-3 flex items-start gap-2 text-xs text-[var(--color-ink-dim)]">
            <input
              type="checkbox"
              className="mt-0.5"
              checked={profile.autoReach}
              onChange={(e) => patchProfile({ autoReach: e.target.checked })}
            />
            <span>
              <span className="text-[var(--color-ink)]">Learn my reach automatically</span>
              <br />
              Adapts to how far you actually move, so the cursor always covers the whole board. Turn
              off only if you want to pin the box by hand.
            </span>
          </label>
          <button
            type="button"
            onClick={() => {
              getActiveSession()?.resetReach();
              toast.success("Reach reset — move around to teach it again");
            }}
            className="mb-3 w-full rounded-lg border border-white/10 px-3 py-1.5 text-xs text-[var(--color-ink-dim)] hover:text-[var(--color-ink)]"
          >
            Reset learned reach
          </button>
          <div
            className={[
              "grid grid-cols-4 gap-2 transition",
              profile.autoReach ? "pointer-events-none opacity-40" : "",
            ].join(" ")}
          >
            {(
              [
                ["Left", "x"],
                ["Top", "y"],
                ["Width", "w"],
                ["Height", "h"],
              ] as const
            ).map(([label, key]) => (
              <label key={key} className="text-[10px] text-[var(--color-ink-dim)]">
                {label}
                <input
                  type="number"
                  min={0.02}
                  max={1}
                  step={0.02}
                  value={profile.activeArea[key].toFixed(2)}
                  onChange={(e) => {
                    const v = Number(e.target.value);
                    if (!Number.isFinite(v)) return;
                    patchProfile({
                      activeArea: { ...profile.activeArea, [key]: Math.min(1, Math.max(0.02, v)) },
                    });
                  }}
                  className="mt-1 w-full rounded-md border border-white/10 bg-black/30 px-2 py-1 text-xs text-[var(--color-ink)] outline-none"
                />
              </label>
            ))}
          </div>
          <label className="mt-3 flex items-center gap-2 text-xs text-[var(--color-ink-dim)]">
            <input
              type="checkbox"
              checked={profile.mirror}
              onChange={(e) => patchProfile({ mirror: e.target.checked })}
            />
            Mirror horizontally (move right → cursor right)
          </label>
        </Section>

        {/* ---------------- camera ---------------- */}
        <Section
          title="Camera"
          hint="Everything stays on this machine — no frame ever leaves the app."
        >
          <select
            value={cameraId ?? ""}
            onChange={(e) => setCameraId(e.target.value || null)}
            className="w-full rounded-md border border-white/10 bg-black/30 px-2 py-1.5 text-xs text-[var(--color-ink)] outline-none"
          >
            <option value="">System default</option>
            {cameras.map((c, i) => (
              <option key={c.deviceId} value={c.deviceId}>
                {c.label || `Camera ${i + 1}`}
              </option>
            ))}
          </select>
          <label className="mt-3 flex items-center gap-2 text-xs text-[var(--color-ink-dim)]">
            <input
              type="checkbox"
              checked={previewOn}
              onChange={(e) => setPreviewOn(e.target.checked)}
            />
            Show the camera thumbnail
          </label>
        </Section>

        <div className="mt-5 flex items-center justify-between border-t border-white/8 pt-4">
          <button
            type="button"
            onClick={() => {
              if (confirm("Reset all Air Board gestures and calibration to defaults?")) {
                resetProfile();
              }
            }}
            className="rounded-lg px-3 py-1.5 text-xs text-red-300 hover:bg-red-500/10"
          >
            Reset everything
          </button>
          <button
            type="button"
            onClick={onClose}
            className="rounded-lg border border-white/10 px-4 py-1.5 text-xs text-[var(--color-ink)] hover:bg-white/5"
          >
            Done
          </button>
        </div>
      </motion.div>
    </div>
  );
}

/* ------------------------------------------------------------------ */

function Section({
  title,
  hint,
  children,
}: {
  title: string;
  hint?: string;
  children: React.ReactNode;
}): JSX.Element {
  return (
    <section className="mb-6">
      <h3 className="text-xs font-semibold uppercase tracking-wide text-[var(--color-ink)]">
        {title}
      </h3>
      {hint && (
        <p className="mb-3 mt-1 text-[11px] leading-relaxed text-[var(--color-ink-dim)]">{hint}</p>
      )}
      {children}
    </section>
  );
}

function Slider({
  label,
  value,
  min,
  max,
  step,
  onChange,
  left,
  right,
  note,
  format,
}: {
  label: string;
  value: number;
  min: number;
  max: number;
  step: number;
  onChange: (v: number) => void;
  left: string;
  right: string;
  note?: string;
  format?: (v: number) => string;
}): JSX.Element {
  return (
    <div className="mb-4">
      <div className="mb-1 flex items-baseline justify-between">
        <span className="text-xs text-[var(--color-ink)]">{label}</span>
        <span className="text-[10px] tabular-nums text-[var(--color-ink-dim)]">
          {format ? format(value) : value.toFixed(2)}
        </span>
      </div>
      <input
        type="range"
        min={min}
        max={max}
        step={step}
        value={value}
        onChange={(e) => onChange(Number(e.target.value))}
        className="w-full accent-[var(--color-accent)]"
      />
      <div className="flex justify-between text-[9px] text-[var(--color-ink-dim)]">
        <span>{left}</span>
        <span>{right}</span>
      </div>
      {note && <p className="mt-1 text-[10px] text-[var(--color-ink-dim)]">{note}</p>}
    </div>
  );
}
